    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    int selectedRow = tblPC.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a PC from the table.");
        return;
    }

    String pcID = tblPC.getValueAt(selectedRow, 0).toString();

    String pcName = txtPCName.getText();
    String pcType = txtPCType.getText();
    String priceText = txtPrice.getText();
    String status = cmbStatus.getSelectedItem().toString();

    if (pcName.isEmpty() || pcType.isEmpty() || priceText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    try {
        double price = Double.parseDouble(priceText);

        String sql = "UPDATE pcs SET pc_name=?, pc_type=?, "
                   + "price_per_hour=?, status=? WHERE id=?";

        try (Connection conn = DataStore.getConnection();
             PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, pcName);
            pst.setString(2, pcType);
            pst.setDouble(3, price);
            pst.setString(4, status);
            pst.setInt(5, Integer.parseInt(pcID));

            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
                "PC updated successfully!");

        loadPCs();
        clearFields();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Price must be a number.",
                "Invalid Price",
                JOptionPane.ERROR_MESSAGE);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Failed to update PC:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    int selectedRow = tblPC.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this, "Please select a PC to delete.");
    return;
}

int choice = JOptionPane.showConfirmDialog(
    this,
    "Are you sure you want to delete this PC?",
    "Delete PC",
    JOptionPane.YES_NO_OPTION
);

if (choice != JOptionPane.YES_OPTION) {
    return;
}

String pcID = tblPC.getValueAt(selectedRow, 0).toString();

try {

    String sql = "DELETE FROM pcs WHERE id = ?";

    try (Connection conn = DataStore.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setInt(1, Integer.parseInt(pcID));
        pst.executeUpdate();
    }

    JOptionPane.showMessageDialog(
        this,
        "PC deleted successfully!"
    );

    loadPCs();
    clearFields();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "Failed to delete PC:\n" + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

