    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblCustomer.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
        this,
        "Please select a customer to delete."
    );
    return;
}

int choice = JOptionPane.showConfirmDialog(
    this,
    "Are you sure you want to delete this customer?",
    "Delete Customer",
    JOptionPane.YES_NO_OPTION
);

if (choice != JOptionPane.YES_OPTION) {
    return;
}

String customerID =
    tblCustomer.getValueAt(selectedRow, 0).toString();

try {

    String sql = "DELETE FROM customers WHERE id=?";

    try (Connection conn = DataStore.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setInt(1, Integer.parseInt(customerID));

        pst.executeUpdate();
    }

    JOptionPane.showMessageDialog(
        this,
        "Customer deleted successfully!"
    );

    loadCustomers();
    clearFields();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "Failed to delete customer:\n" + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String customerName = txtCustomerName.getText();
String contact = txtContact.getText();
String email = txtEmail.getText();

if (customerName.isEmpty() || contact.isEmpty() || email.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Please fill in all fields."
    );
    return;
}

try {

    String sql = "INSERT INTO customers "
               + "(customer_name, contact, email) "
               + "VALUES (?, ?, ?)";

    try (Connection conn = DataStore.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, customerName);
        pst.setString(2, contact);
        pst.setString(3, email);

        pst.executeUpdate();
    }

    JOptionPane.showMessageDialog(
        this,
        "Customer added successfully!"
    );

    loadCustomers();
    clearFields();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "Failed to add customer:\n" + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int selectedRow = tblCustomer.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
        this,
        "Please select a customer from the table."
    );
    return;
}

String customerID =
    tblCustomer.getValueAt(selectedRow, 0).toString();

String customerName = txtCustomerName.getText();
String contact = txtContact.getText();
String email = txtEmail.getText();

if (customerName.isEmpty() ||
    contact.isEmpty() ||
    email.isEmpty()) {

    JOptionPane.showMessageDialog(
        this,
        "Please fill in all fields."
    );
    return;
}

try {

    String sql = "UPDATE customers SET "
               + "customer_name=?, contact=?, email=? "
               + "WHERE id=?";

    try (Connection conn = DataStore.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, customerName);
        pst.setString(2, contact);
        pst.setString(3, email);
        pst.setInt(4, Integer.parseInt(customerID));

        pst.executeUpdate();
    }

    JOptionPane.showMessageDialog(
        this,
        "Customer updated successfully!"
    );

    loadCustomers();
    clearFields();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "Failed to update customer:\n" + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

