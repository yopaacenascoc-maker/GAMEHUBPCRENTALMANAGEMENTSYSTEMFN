private void updateNumbers() {

    int totalPCs = 0;
    int availablePCs = 0;
    int rentedPCs = 0;
    int customers = 0;

    try (Connection conn = DataStore.getConnection()) {

        // Total PCs
        String sqlTotal = "SELECT COUNT(*) FROM pcs";

        try (PreparedStatement pst = conn.prepareStatement(sqlTotal);
             ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                totalPCs = rs.getInt(1);
            }
        }

        // Available PCs
        String sqlAvailable =
                "SELECT COUNT(*) FROM pcs WHERE status = 'Available'";

        try (PreparedStatement pst = conn.prepareStatement(sqlAvailable);
             ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                availablePCs = rs.getInt(1);
            }
        }

        // Rented PCs
        String sqlRented =
                "SELECT COUNT(*) FROM pcs WHERE status = 'Rented'";

        try (PreparedStatement pst = conn.prepareStatement(sqlRented);
             ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                rentedPCs = rs.getInt(1);
            }
        }

        // Customers
        String sqlCustomers =
                "SELECT COUNT(*) FROM customers";

        try (PreparedStatement pst = conn.prepareStatement(sqlCustomers);
             ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                customers = rs.getInt(1);
            }
        }

        lblTotalPCs1.setText(String.valueOf(totalPCs));
        lblAvailablePCs1.setText(String.valueOf(availablePCs));
        lblRentedPCs1.setText(String.valueOf(rentedPCs));
        lblCustomers1.setText(String.valueOf(customers));

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Failed to load dashboard numbers:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
