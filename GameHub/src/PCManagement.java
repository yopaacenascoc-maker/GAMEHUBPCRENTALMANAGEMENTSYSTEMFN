    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
    String pcName = txtPCName.getText();
String pcType = txtPCType.getText();
String priceText = txtPrice.getText();
String status = cmbStatus.getSelectedItem().toString();

if (pcName.isEmpty() || pcType.isEmpty() || priceText.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please fill in all fields.");
    return;
}

try {

    double price = Double.parseDouble(priceText);

    String sql = "INSERT INTO pcs "
               + "(pc_name, pc_type, price_per_hour, status) "
               + "VALUES (?, ?, ?, ?)";

    try (Connection conn = DataStore.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, pcName);
        pst.setString(2, pcType);
        pst.setDouble(3, price);
        pst.setString(4, status);

        pst.executeUpdate();
    }

    JOptionPane.showMessageDialog(this, "PC added successfully!");

    loadPCs();
    clearFields();

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
        this,
        "Price must be a number.",
        "Invalid Price",
        JOptionPane.ERROR_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "Failed to add PC:\n" + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

